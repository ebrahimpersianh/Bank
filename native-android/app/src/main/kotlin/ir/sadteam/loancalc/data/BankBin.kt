/** [cardNumber] هر رشته‌ای می‌تونه باشه (با فاصله/خط‌تیره)؛ فقط ارقامش تمیز و ۶تای اول چک می‌شه.
 * کمتر از ۶ رقم یا BINِ ناشناس → null (یعنی کاربر باید دستی وارد کنه). */
fun detectBankByCardNumber(cardNumber: String): String? {
    val digits = cardNumber.filter { it.isDigit() }
    if (digits.length < 6) return null
    return RemoteApp.config.bins[digits.take(6)] ?: bankBins[digits.take(6)]
}

