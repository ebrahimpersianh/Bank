package ir.sadteam.loancalc.data.coin

/**
 * **قلمِ برجسته‌ی هفته** - فریمِ `78c`، قاعده در `78g`.
 *
 * انتخاب **دستی نیست و سرورِ محتوا ندارد**: اولین قلمِ نداشته‌ی کاربر از یک ترتیبِ
 * ثابت. پس هیچ تاریخی، هیچ فراخوانِ شبکه‌ای و هیچ پنلِ ادمینی لازم نیست، و کارت
 * برای هر کاربر چیزِ متفاوتی نشان می‌دهد.
 *
 * ترتیب عمدی است: گران‌ترین یا تازه‌ترین قلم اول نمی‌آید، بلکه قلمی اول می‌آید که
 * **نوعِ تازه** معرفی می‌کند (پس‌زمینه)، بعد قلم‌های هم‌جنس.
 */
val FEATURED_ORDER = listOf(
    "bg_aurora",
    "theme:saffron",
    "theme:cobalt",
    "theme:clay",
    "theme:plum",
    "icon:coin",
)

/**
 * `null` یعنی **کارت نمی‌آید**.
 *
 * ⚠️ برای کسی که همه را دارد، جای کارت خالی می‌مانَد و پیامِ «همه را داری» **نمی‌آید**.
 * تبریکِ بی‌کار است: کاری برای انجام پیشنهاد نمی‌کند و ارتفاعِ بالای ویترین را می‌گیرد.
 */
fun featuredItemId(owned: Set<String>): String? = FEATURED_ORDER.firstOrNull { it !in owned }
