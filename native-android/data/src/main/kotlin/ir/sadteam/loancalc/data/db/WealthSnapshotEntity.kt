package ir.sadteam.loancalc.data.db

import androidx.room.Entity
import androidx.room.PrimaryKey

/**
 * **عکسِ روزانه‌ی دارایی** - خواسته‌ی کاربر (۳۱ شهریور: «قیمت‌ها را هر روز ذخیره کن»).
 *
 * 🚨 چرا لازم شد: نمودارِ روندِ کارتِ دارایی تا امروز **رو به عقب** از موجودیِ امروز
 * بازسازی می‌شد. آن روش برای پولِ نقد درست است (تراکنش‌ها را داریم) ولی برای طلا و ارز
 * نه: قیمتِ **دیروزِ** سکه هیچ‌جا ذخیره نمی‌شد، پس ارزشِ دیروزِ دارایی قابلِ بازسازی نبود.
 * با این جدول، از امروز به بعد هر روز یک ردیف نوشته می‌شود و نمودار کم‌کم واقعی می‌شود.
 *
 * ⚠️ **گذشته ساخته نمی‌شود.** ردیف‌ها از روزِ نصبِ این نسخه شروع می‌شوند؛ هیچ داده‌ی
 * تاریخیِ ساختگی تولید نمی‌کنیم.
 *
 * ⚠️ کلیدِ اصلی **خودِ روز** است (`۱۴۰۴-۰۶-۳۱`)، نه یک شناسه‌ی زمانی: هر روز دقیقاً یک
 * ردیف. با `@Upsert`، چند بار بازکردنِ تب در یک روز فقط همان ردیف را تازه می‌کند -
 * همان درسِ «شناسه‌ی زمانی در حلقه» که یک‌بار تراکنش‌ها را روی هم نوشت.
 *
 * مبلغ‌ها **ریال**اند مثلِ کلِ دیتابیس.
 */
@Entity(tableName = "wealth_snapshots")
data class WealthSnapshotEntity(
    /** `yyyy-MM-dd`ِ جلالی، مثلِ `۱۴۰۴-۰۶-۳۱` ولی با رقمِ لاتین تا مرتب‌سازی درست بماند. */
    @PrimaryKey val dateKey: String,
    /** جمعِ موجودیِ حساب‌ها - از تراکنش‌ها می‌آید، پس بازسازی‌شدنی هم هست. */
    val cashRial: Double,
    /** ارزشِ طلا/ارز/رمزارز/سایر **با قیمتِ همان روز** - تنها چیزی که بازسازی‌شدنی نیست. */
    val assetsRial: Double,
    val createdAt: String,
) {
    val totalRial: Double get() = cashRial + assetsRial
}
