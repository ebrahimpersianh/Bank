package ir.sadteam.loancalc.data

/**
 * پلِ «داده‌ی وام عوض شد» از `:data` به `:app`.
 *
 * ویجت در `:app` زندگی می‌کند و `:data` آن را نمی‌بیند (وابستگی یک‌طرفه است)، پس
 * `LoanRepository` نمی‌تواند مستقیم `LoanWidget.updateAll()` را صدا بزند. به‌جایش این‌جا
 * یک قلاب می‌گذارد و `:app` موقعِ راه‌اندازی پُرش می‌کند.
 *
 * چرا این‌جا و نه در UI: بی این، **هر صفحه‌ای** که قسطی را عوض می‌کند باید یادش بماند
 * ویجت را هم تازه کند - و یکی از آن‌ها بالاخره یادش می‌رود. یک نقطه‌ی نوشتن، مثلِ همان
 * قاعده‌ی `withPaidCount`.
 */
object LoanDataChange {
    /** `:app` این را ست می‌کند؛ تا وقتی خالی است هیچ اتفاقی نمی‌افتد (تست‌ها هم بی‌اثر می‌مانند). */
    @Volatile
    var onChanged: (() -> Unit)? = null

    fun notifyChanged() {
        onChanged?.invoke()
    }
}
